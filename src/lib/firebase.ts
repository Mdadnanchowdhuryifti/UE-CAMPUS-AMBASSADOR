export function normalizeEmailKey(email: string): string {
  return email
    .trim()
    .toLowerCase()
    .replace(/@/g, '_at_')
    .replace(/\./g, '_dot_')
    .replace(/\+/g, '_plus_');
}

export const MAIN_DEVELOPER_EMAIL_KEYS = MAIN_DEVELOPER_EMAILS.map(normalizeEmailKey);

export enum OperationType {
  CREATE = 'create',
  UPDATE = 'update',
  DELETE = 'delete',
  LIST = 'list',
  GET = 'get',
  WRITE = 'write',
}

export interface FirestoreErrorInfo {
  error: string;
  operationType: OperationType;
  path: string | null;
  authInfo: {
    userId?: string | null;
    email?: string | null;
    emailVerified?: boolean | null;
    isAnonymous?: boolean | null;
    tenantId?: string | null;
    providerInfo?: {
      providerId?: string | null;
      email?: string | null;
    }[];
  };
}

type FirestoreErrorObserver = (info: FirestoreErrorInfo) => void;
let firestoreErrorObserver: FirestoreErrorObserver | null = null;

export function registerFirestoreErrorObserver(observer: FirestoreErrorObserver | null) {
  firestoreErrorObserver = observer;
}

export function handleFirestoreError(
  error: unknown,
  operationType: OperationType,
  path: string | null
): never {
  const errInfo: FirestoreErrorInfo = {
    error: error instanceof Error ? error.message : String(error),
    authInfo: {
      userId: auth.currentUser?.uid ?? null,
      email: auth.currentUser?.email ?? null,
      emailVerified: auth.currentUser?.emailVerified ?? null,
      isAnonymous: auth.currentUser?.isAnonymous ?? null,
      tenantId: auth.currentUser?.tenantId ?? null,
      providerInfo:
        auth.currentUser?.providerData?.map((provider) => ({
          providerId: provider.providerId,
          email: provider.email,
        })) || [],
    },
    operationType,
    path,
  };
  console.error('Firestore Error: ', JSON.stringify(errInfo));
  if (firestoreErrorObserver && path !== 'error_logs' && !path?.startsWith('error_logs/')) {
    try {
      firestoreErrorObserver(errInfo);
    } catch {
      // ignore observer errors
    }
  }
  throw new Error(JSON.stringify(errInfo));
}

